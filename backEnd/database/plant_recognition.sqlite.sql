-- ============================================================
-- 1. 创建植物信息表 (plants)
-- ============================================================
CREATE TABLE IF NOT EXISTS plants (
    -- 主键
    id INTEGER PRIMARY KEY AUTOINCREMENT,  -- 植物ID，自增主键
    
    -- 分类标识
    class_id INTEGER NOT NULL UNIQUE,  -- 模型类别ID，对应模型输出的索引(0-49)
    
    -- 基本信息
    chinese_name TEXT NOT NULL,  -- 中文名称
    english_name TEXT,  -- 英文名称
    scientific_name TEXT,  -- 拉丁学名
    
    -- 分类信息
    family TEXT,  -- 科名(中文)
    genus TEXT,  -- 属名(中文)
    
    -- 特征描述
    description TEXT,  -- 植物详细描述
    characteristics TEXT,  -- 形态特征
    flowering_period TEXT,  -- 花期
    
    -- 养护信息
    care_tips TEXT,  -- 养护建议(浇水、光照、施肥等)
    difficulty_level INTEGER DEFAULT 2,  -- 养护难度: 1-简单, 2-中等, 3-困难
    
    -- 图片信息
    image_url TEXT,  -- 示例图片URL或本地路径
    
    -- 状态管理
    status INTEGER DEFAULT 1,  -- 状态: 0-禁用, 1-启用
    view_count INTEGER DEFAULT 0,  -- 浏览次数
    
    -- 时间戳
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,  -- 创建时间
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP  -- 更新时间
);

-- 创建索引优化查询
CREATE INDEX IF NOT EXISTS idx_plants_class_id ON plants(class_id);
CREATE INDEX IF NOT EXISTS idx_plants_chinese_name ON plants(chinese_name);
CREATE INDEX IF NOT EXISTS idx_plants_family ON plants(family);
CREATE INDEX IF NOT EXISTS idx_plants_status ON plants(status);

-- ============================================================
-- 2. 创建识别历史表 (recognition_history)
-- ============================================================
CREATE TABLE IF NOT EXISTS recognition_history (
    -- 主键
    id INTEGER PRIMARY KEY AUTOINCREMENT,  -- 记录ID，自增主键
    
    -- 关联信息(不使用外键约束，通过应用层维护)
    plant_id INTEGER,  -- 关联的植物ID(plants表)
    class_id INTEGER NOT NULL,  -- 识别的类别ID
    
    -- 识别结果
    confidence REAL NOT NULL,  -- 置信度(0-1之间)
    plant_name TEXT,  -- 识别的植物名称(冗余存储，方便查询)
    
    -- 图片信息
    image_path TEXT NOT NULL,  -- 识别的图片本地存储路径
    
    -- 位置信息(可选)
    latitude REAL,  -- 纬度
    longitude REAL,  -- 经度
    location_name TEXT,  -- 位置描述
    
    -- 用户标识(支持游客模式)
    user_id TEXT,  -- 用户ID或设备标识
    
    -- 收藏标记
    is_favorite INTEGER DEFAULT 0,  -- 是否收藏: 0-否, 1-是
    notes TEXT,  -- 用户备注
    
    -- 时间戳
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,  -- 识别时间
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP  -- 更新时间
);

-- 创建索引优化查询
CREATE INDEX IF NOT EXISTS idx_history_plant_id ON recognition_history(plant_id);
CREATE INDEX IF NOT EXISTS idx_history_class_id ON recognition_history(class_id);
CREATE INDEX IF NOT EXISTS idx_history_user_id ON recognition_history(user_id);
CREATE INDEX IF NOT EXISTS idx_history_created_at ON recognition_history(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_history_is_favorite ON recognition_history(is_favorite);

